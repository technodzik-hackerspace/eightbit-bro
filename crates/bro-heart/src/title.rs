impl Title {
    pub fn from_number(number: u16) -> Option<Title> {
        TITLES.iter().find(|(_, n, _)| *n == number).map(|(t, _, _)| *t)
    }

    pub fn number(self) -> u16 {
        self as u16
    }

    /// The name as the menu shows it.
    pub fn name(self) -> &'static str {
        TITLES.iter().find(|(t, _, _)| *t == self).map(|(_, _, name)| *name).unwrap()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_and_names_are_consistent() {
        for (i, (title, number, name)) in TITLES.iter().enumerate() {
            assert_eq!(title.number(), *number);
            assert_eq!(title.name(), *name);
            assert_eq!(Title::from_number(*number), Some(*title));
            assert!(i == 0 || TITLES[i - 1].1 < *number, "sorted, unique");
        }
        assert_eq!(Title::from_number(1).unwrap().name(), "ADVENTURE ISLAND");
        assert_eq!(Title::from_number(267), Some(Title::TetrisIi));
        assert_eq!(Title::from_number(0), None);
    }
}
